/** Map a child's age in years onto the plan's age bands (4-6, 6-9, 9-12, 12-15). */
export function apaGroupIndexForAge(age: number): number {
  if (!Number.isFinite(age) || age <= 0) return 0
  if (age < 6) return 0
  if (age < 9) return 1
  if (age < 12) return 2
  return 3
}
